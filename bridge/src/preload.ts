// The only thing the window can reach. Runs in the sandboxed preload world, so it may only require 'electron'.
import { contextBridge, ipcRenderer } from 'electron';

type Result = Promise<{ ok: boolean; text: string }>;

contextBridge.exposeInMainWorld('bridge', {
  minimize: (): Promise<void> => ipcRenderer.invoke('win-minimize'),
  closeToTray: (): Promise<void> => ipcRenderer.invoke('win-close'),
  getState:(): Promise<unknown> => ipcRenderer.invoke('state'),
  onState: (cb: (state: unknown) => void): void => { ipcRenderer.on('state', (_e, state) => cb(state)); },
  pair: (site: string, code: string): Promise<{ ok: boolean; error?: string }> => ipcRenderer.invoke('pair', String(site), String(code)),
  unpair: (): Promise<void> => ipcRenderer.invoke('unpair'),
  setObs: (enabled: boolean, address: string, password?: string, startReplay?: boolean): Promise<{ ok: boolean; error?: string }> => ipcRenderer.invoke('obs-settings', !!enabled, String(address), typeof password === 'string' ? password : undefined, !!startReplay),
  setStartWithWindows: (on: boolean): Promise<void> => ipcRenderer.invoke('start-with-windows', !!on),
  setAlerts: (on: boolean): Promise<void> => ipcRenderer.invoke('alerts', !!on),
  testMixItUp: (name: string): Result => ipcRenderer.invoke('test-mix', String(name)),
  testChat: (): Result => ipcRenderer.invoke('test-chat'),
  testObs: (): Result => ipcRenderer.invoke('test-obs'),
  runChecklist: (): Result => ipcRenderer.invoke('checklist'),
  startMixItUp: (): Result => ipcRenderer.invoke('start-mix'),
  chooseMixItUp: (): Result => ipcRenderer.invoke('choose-mix'),
  setStartMixItUp: (on: boolean): Promise<void> => ipcRenderer.invoke('start-mix-with-bridge', !!on),
  setFeed: (f: Record<string, unknown>): Promise<void> => ipcRenderer.invoke('set-feed', f),
  setSummary: (on: boolean): Promise<void> => ipcRenderer.invoke('set-summary', !!on),
  setScenePause: (cfg: { on: boolean; scenes: string[] }): Promise<void> => ipcRenderer.invoke('set-scene-pause', cfg),
  setObsStats: (map: Record<string, string>): Promise<void> => ipcRenderer.invoke('set-obs-stats', map),
  setNotice: (kind: string, on: boolean): Promise<void> => ipcRenderer.invoke('set-notice', kind, !!on),
  setStartObs: (on: boolean): Promise<void> => ipcRenderer.invoke('start-obs-with-bridge', !!on),
  chooseObsExe: (): Result => ipcRenderer.invoke('choose-obs'),
  happyStart: (minutes: number, kind: string, percent: number): Result => ipcRenderer.invoke('happy-start', Number(minutes), String(kind), Number(percent)),
  happyEnd: (): Result => ipcRenderer.invoke('happy-end'),
  openLogs: (): Result => ipcRenderer.invoke('open-logs'),
  openBackups: (): Result => ipcRenderer.invoke('open-backups'),
  copyDiagnostics: (): Result => ipcRenderer.invoke('copy-diagnostics'),
  checkUpdate: (): Result => ipcRenderer.invoke('check-update'),
  setPause: (on: boolean): Result => ipcRenderer.invoke('pause', !!on),
  copyButton: (i: number): Result => ipcRenderer.invoke('copy-button', Number(i)),
  setHotkeys: (map: Record<string, string>): Promise<Record<string, string>> => ipcRenderer.invoke('set-hotkeys', map),
  getQueue: (): Promise<{ ok: boolean; text: string; rows: { id: string; kind: string; username: string; pack: string; waitedS: number }[] }> => ipcRenderer.invoke('queue'),
  queueDo: (what: 'skip' | 'clear'): Result => ipcRenderer.invoke('queue-do', what),
  staff: (req: Record<string, unknown>): Promise<{ ok: boolean; text: string; data?: Record<string, unknown> }> => ipcRenderer.invoke('staff', req),
  staffTrading: (pause: boolean): Result => ipcRenderer.invoke('staff-trading', !!pause),
  restartToUpdate: (): Promise<void> => ipcRenderer.invoke('restart-to-update'),
  openRelease: (): Promise<void> => ipcRenderer.invoke('open-release'),
  openReleases: (): Promise<void> => ipcRenderer.invoke('open-releases'),
  whatsNew: (): Promise<{ ok: boolean; notes: { version: string; blocks: { kind: string; text: string }[] }[] }> => ipcRenderer.invoke('whats-new'),
  openCommit: (): Promise<void> => ipcRenderer.invoke('open-commit'),
  dismissUpdated: (): Promise<void> => ipcRenderer.invoke('dismiss-updated'),
});
